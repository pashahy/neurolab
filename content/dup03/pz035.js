// Проверка вызовов в python-тестах: каждый вызов сравнивается с ожидаемым значением (и типом),
// а в сообщении видно, что вернула функция студента, — разница в один символ не теряется.
const calls = (pairs, approx = false) => [
  'for __call, __e in [',
  ...pairs.map(([c, e]) => `    (${JSON.stringify(c)}, ${e}),`),
  ']:',
  '    __r = eval(__call)',
  approx ? '    __ok = type(__r) in (int, float) and abs(__r - __e) < 1e-6' : '    __ok = __r == __e and type(__r) is type(__e)',
  '    assert __ok, f"{__call}: ожидалось {__e!r}, функция вернула {__r!r}"',
].join('\n');

// Проверка аннотаций функции: в сообщении — ожидаемый заголовок и фактические аннотации.
const ann = (fn, want, header) => `__a = ${fn}.__annotations__
assert __a == ${want}, f"Ожидается заголовок ${header}. Сейчас аннотации: {__a!r}"`;

// Проверка строки документации: есть, первая строка — краткое описание с точкой.
const doc = fn => `__d = ${fn}.__doc__
assert __d is not None and __d.strip() != "", "У функции ${fn} нет строки документации: она должна быть первой инструкцией тела"
__f = __d.strip().splitlines()[0].strip()
assert __f.endswith("."), f"Краткое описание ${fn} — первая строка документации — должно заканчиваться точкой. Сейчас: {__f!r}"`;

// Сравнение строк вывода программы с ожидаемыми.
const out = (want, what) => `__l = __out__.strip().splitlines()
assert __l == ${JSON.stringify(want)}, f"${what}: ожидалось ${JSON.stringify(want).replace(/"/g, "'")}. Ваша программа вывела: {__l!r}"`;

