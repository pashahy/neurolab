// Тесты с файлами. Файлы создаёт и удаляет сам тест (до и после проверки), поэтому запуски не влияют друг на друга.
// Внутри теста open() заменён обёрткой: любой вызов открытия текстового файла без encoding="utf-8" считается ошибкой
// (в браузере кодировка по умолчанию UTF-8, и без такой проверки забытый encoding остался бы незамеченным).
const ind = s => s.split('\n').map(l => '    ' + l).join('\n');
const ftest = (files, body, clean = []) => {
  const names = clean.concat(Object.keys(files), body.match(/no_such[\w.]*/g) || []);
  const setup = Object.entries(files).map(([n, c]) =>
    `with __orig_open(${JSON.stringify(n)}, "w", encoding="utf-8", newline="") as __f:\n    __f.write(${JSON.stringify(c)})`);
  return [
    'import os, builtins',
    `__names = ${JSON.stringify(names)}`,
    'def __clean():',
    '    for __n in __names:',
    '        if os.path.exists(__n):',
    '            os.remove(__n)',
    '__orig_open = builtins.open',
    'def __open(file, mode="r", *a, **kw):',
    '    if "b" not in mode:',
    '        __enc = kw.get("encoding") if "encoding" in kw else (a[1] if len(a) > 1 else None)',
    '        assert isinstance(__enc, str) and __enc.lower().replace("-", "").replace("_", "") == "utf8", f"open({file!r}, {mode!r}): укажите кодировку явно: encoding=\'utf-8\'"',
    '    return __orig_open(file, mode, *a, **kw)',
    'def __read(n):',
    '    if not os.path.exists(n):',
    '        return "(файла нет)"',
    '    with __orig_open(n, encoding="utf-8") as __f:',
    '        return __f.read()',
    '__clean()',
    'try:',
    '    builtins.open = __open',
    ind([...setup, body].join('\n')),
    'finally:',
    '    builtins.open = __orig_open',
    '    __clean()',
  ].join('\n');
};
