// Проверка вызовов в python-тестах: каждый вызов сравнивается с ожидаемым значением (и типом),
// а в сообщении видно, что вернула функция студента, — разница в один символ не теряется.
const calls = (pairs, approx = false) => [
  'for __call, __e in [',
  ...pairs.map(([c, e]) => `    (${JSON.stringify(c)}, ${e}),`),
  ']:',
  '    __r = eval(__call)',
  approx ? '    __ok = type(__r) in (int, float) and abs(__r - __e) < 1e-6' : '    __ok = __r == __e and type(__r) is type(__e)',
  '    assert __ok, f"{__call}: ожидалось {__e!r}, функция вернула {__r!r}"',
].join('\n');

